// Global translation lookup helper
function t(key, params = {}) {
  const lang = (typeof currentLang !== 'undefined' && currentLang) ? currentLang : 'th';
  let str = TRANSLATIONS[lang] && TRANSLATIONS[lang][key];
  if (!str) {
    str = (TRANSLATIONS['th'] && TRANSLATIONS['th'][key]) ||
          (TRANSLATIONS['en'] && TRANSLATIONS['en'][key]) ||
          key;
  }
  if (params && typeof params === 'object') {
    Object.keys(params).forEach(p => {
      str = str.replace(new RegExp('\\{' + p + '\\}', 'g'), params[p]);
    });
  }
  return str;
}

function getLocaleCode(lang = currentLang) {
  const match = SUPPORTED_LANGUAGES.find(l => l.code === lang);
  return match ? match.locale : 'th-TH';
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { SUPPORTED_LANGUAGES, TRANSLATIONS, t, getLocaleCode };
}
